// Generates the app icons in public/ from the logo's brand tokens and the Saira ExtraBold font
// (design: docs/design/approvals.md, 2026-10-07). Run `npm run icons` after changing either.
//
// The icon is the logo in miniature: the teal-gradient film frame with sprocket holes, and "DC"
// with D filled in the gradient and C as the gold outline (like DEEP and CUTS), on the dark
// app-icon plate. The letters are converted to vector paths, because a favicon can't load fonts.
//
// Outputs (committed, so the app needs no build step for them):
// - favicon.svg: rounded plate, for browser tabs
// - apple-touch-icon.png (180), icon-192.png, icon-512.png: square plate (phones round the
//   corners themselves), rendered from the SVG with Playwright's Chromium
// - manifest.webmanifest: name, icons and colors for "Add to Home Screen"
import { chromium } from '@playwright/test'
import { readFileSync, writeFileSync } from 'node:fs'
import opentype from 'opentype.js'

const tokens = JSON.parse(readFileSync('build/tokens/tokens.json', 'utf8'))
const color = {
  top: tokens['brand-logo-gradient-start'],
  bottom: tokens['brand-logo-gradient-end'],
  gold: tokens['brand-logo-cuts'],
  plate: tokens['brand-logo-ink'],
  // The app's page color, for the home-screen splash and browser UI.
  surface: tokens['color-surface-default'],
}

// ---- Letters: "D" and "C" from Saira ExtraBold, as paths on a 64×64 grid ----
const file = readFileSync('node_modules/@fontsource/saira/files/saira-latin-800-normal.woff')
const font = opentype.parse(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength))
const em = font.unitsPerEm
const capHeight = font.tables.os2.sCapHeight / em
const advance = (ch) => font.charToGlyph(ch).advanceWidth / em
const GAP = 0.6
// The frame's window is 34px wide; the pair is at most 29px wide and at most 21px tall.
const size = Math.min(21 / capHeight, (29 - GAP) / (advance('D') + advance('C')))
const width = (advance('D') + advance('C')) * size + GAP
const left = 32 - width / 2
const baseline = 32 + (size * capHeight) / 2
const d = font.getPath('D', left, baseline, size).toPathData(2)
const c = font.getPath('C', left + advance('D') * size + GAP, baseline, size).toPathData(2)

// ---- Frame: 9px side bars with three sprocket holes each, 4px top and bottom bars ----
const holes = [15, 29.5, 44]
  .flatMap((y) => [`M8.5 ${y}h3.5v5h-3.5z`, `M52 ${y}h3.5v5h-3.5z`])
  .join('')
const frame = `M6 8h52v48H6z M15 12h34v40H15z ${holes}`

/** The icon as SVG. `radius` rounds the plate (0 = square, for phone home screens). */
const svg = (
  radius,
) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="Deep Cuts">
  <!-- GENERATED by scripts/generate-icons.mjs (npm run icons). Do not edit by hand. -->
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${color.top}"/>
      <stop offset="1" stop-color="${color.bottom}"/>
    </linearGradient>
  </defs>
  <rect width="64" height="64" rx="${radius}" fill="${color.plate}"/>
  <path d="${frame}" fill="url(#g)" fill-rule="evenodd"/>
  <path d="${d}" fill="url(#g)"/>
  <path d="${c}" fill="none" stroke="${color.gold}" stroke-width="1.4" stroke-linejoin="round"/>
</svg>
`

writeFileSync('public/favicon.svg', svg(14))

// ---- PNGs: render the square version at each size ----
const browser = await chromium.launch()
const page = await browser.newPage()
for (const [name, px] of [
  ['apple-touch-icon.png', 180],
  ['icon-192.png', 192],
  ['icon-512.png', 512],
]) {
  await page.setViewportSize({ width: px, height: px })
  await page.setContent(
    `<body style="margin:0">${svg(0).replace('<svg ', `<svg width="${px}" height="${px}" `)}</body>`,
  )
  await page.screenshot({ path: `public/${name}`, omitBackground: true })
}
await browser.close()

writeFileSync(
  'public/manifest.webmanifest',
  JSON.stringify(
    {
      name: 'Deep Cuts',
      short_name: 'Deep Cuts',
      description: 'A fast, one-thumb movie tracker that surfaces deep cuts.',
      start_url: '/',
      display: 'standalone',
      background_color: color.surface,
      theme_color: color.surface,
      icons: [
        { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
        { src: '/icon-512.png', sizes: '512x512', type: 'image/png' },
      ],
    },
    null,
    2,
  ) + '\n',
)
console.log('wrote public/favicon.svg, apple-touch-icon.png, icon-192.png, icon-512.png, manifest')
